--[[
    vanagear: the server's item, augment and weaponskill tables, loaded once on first use.
    The tables themselves are generated by tools/gearstats/build.py from the Vanadreams server.
]]--

local data = {};

local root = string.format('%saddons\\vanagear\\data\\', AshitaCore:GetInstallPath());
local cache = {};

local function load(name)
    if (cache[name] == nil) then
        local chunk, err = loadfile(root .. name .. '.lua');
        if (chunk == nil) then
            print(chat.header('vanagear') .. chat.error('Could not read data\\' .. name .. '.lua: ' .. tostring(err)));
            cache[name] = {};
        else
            cache[name] = chunk();
        end
    end
    return cache[name];
end

data.Items = function() return load('items'); end
data.Augments = function() return load('augments'); end
data.Weaponskills = function() return load('weaponskills'); end
data.Abilities = function() return load('abilities'); end
data.Traits = function() return load('traits'); end
data.Gifts = function() return load('gifts'); end
data.GearSets = function() return load('gearsets'); end
data.Latents = function() return load('latents'); end
data.WsElements = function() return load('wselements'); end
-- the stat an enfeebling spell reads (Paralyze II -> { stat = 'MND', saboteur = true }), nil if not one
data.Enfeeble = function(name)
    return load('enfeebles')[string.gsub(string.lower(name or ''), '[^%l%d]', '')];
end
-- the element a weaponskill's damage takes (Aeolian Edge -> 'Wind'), nil for a physical one
data.WsElement = function(name)
    return load('wselements')[string.gsub(string.lower(name or ''), '[^%l%d]', '')];
end

-- mod name -> server mod id, and back
local modIds = nil;
data.ModId = function(name)
    if (modIds == nil) then
        modIds = {};
        for id, modName in pairs(load('mods')) do
            modIds[modName] = id;
        end
    end
    return modIds[name];
end
data.ModName = function(id)
    return load('mods')[id] or ('MOD_' .. tostring(id));
end

-- The server's equip slot bits, by LuAshitacast slot index (1 Main ... 16 Back; server slot = index - 1).
data.SlotBit = {};
for i = 1, 16 do
    data.SlotBit[i] = bit.lshift(1, i - 1);
end

-- The pet mod types each job's pets read, besides 0 (every pet).
data.PetTypes = {
    BST = { 0 },
    SMN = { 0, 1 },
    DRG = { 0, 2 },
    PUP = { 0, 3, 4, 5, 6, 7 },
    GEO = { 0, 8 },
};

return data;
