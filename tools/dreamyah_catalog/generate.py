"""Writes addons/dreamyah/data/catalog.lua: every item the Vanadreams Auction House can list.

DreamyAH used to ask the server for this list each session, about 136 packets, and could not search until the last
one arrived. The list only changes when the server's item table does, so it ships with the addon instead. Run this
whenever sql/item_basic.sql changes on the server (an AH category added or changed), then bump the addon version in
catalog.json and the launcher's bundled copy.

It keeps the same items the server's catalog request does (src/map/utils/dreamy_ah_service.cpp, GetCatalog): an AH
category other than 0 and no NOAUCTION flag.

    python tools/dreamyah_catalog/generate.py D:\\Workshop\\Git\\vanadreams\\sql\\item_basic.sql
"""
import re
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parents[2] / "addons" / "dreamyah" / "data" / "catalog.lua"
NOAUCTION = 0x40


def value(token, names):
    token = token.strip()
    return names[token[1:]] if token.startswith("@") else int(token)


def catalog(sql):
    names, items = {}, []
    row = re.compile(r"INSERT INTO `item_basic` VALUES \((\d+),\d+,'(?:[^'\\]|\\.)*','(?:[^'\\]|\\.)*','(?:[^'\\]|\\.)*',"
                     r"([^,]+),(\d+),([^,]+),([^,]+),\d+\);")
    for line in sql.splitlines():
        m = re.match(r"SET @(\w+)\s*=\s*(\d+);", line)
        if m:
            names[m.group(1)] = int(m.group(2))
            continue
        m = row.match(line)
        if not m:
            continue
        flags = sum(value(t, names) for t in m.group(4).split("|"))
        category = value(m.group(5), names)
        if category != 0 and not flags & NOAUCTION:
            items.append((int(m.group(1)), category, int(m.group(3))))
    return sorted(items)


def main():
    sql = Path(sys.argv[1]).read_text(encoding="utf-8")
    items = catalog(sql)
    lines = ["-- Generated by tools/dreamyah_catalog/generate.py from the server's sql/item_basic.sql. Do not edit.",
             "-- itemId, AH category, stack size, repeated.",
             "return {"]
    for i in range(0, len(items), 8):
        lines.append("    " + " ".join("%d,%d,%d," % item for item in items[i:i + 8]))
    lines.append("}")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print("%d items written to %s" % (len(items), OUT))


if __name__ == "__main__":
    main()
